/** يتعرّف على المنصة تلقائيًا من الرابط. */
export function detectPlatform(href?: string): Platform {
  const h = (href ?? "").toLowerCase();
  if (!h) return "link";
  if (/facebook\.com|fb\.me|fb\.com/.test(h)) return "facebook";
  if (/instagram\.com|instagr\.am/.test(h)) return "instagram";
  if (/tiktok\.com/.test(h)) return "tiktok";
  if (/twitter\.com|x\.com/.test(h)) return "x";
  if (/youtube\.com|youtu\.be/.test(h)) return "youtube";
  if (/t\.me|telegram/.test(h)) return "telegram";
  if (/wa\.me|whatsapp/.test(h)) return "whatsapp";
  if (/snapchat\.com/.test(h)) return "snapchat";
  if (/linkedin\.com/.test(h)) return "linkedin";
  if (/discord\.(gg|com)/.test(h)) return "discord";
  return "link";
}

